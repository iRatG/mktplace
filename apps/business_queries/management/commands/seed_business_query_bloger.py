class Command(BaseCommand):
    help = "Загружает второй раунд опросника по ручному флоу регистрации юрлиц (task/bloger 12092026)"

    def handle(self, *args, **options):
        existing = BusinessQuery.objects.filter(source_task_path=SOURCE_TASK_PATH).first()
        if existing:
            self.stdout.write(self.style.WARNING(f"Опросник уже существует: {existing.title}"))
            self.stdout.write(f"  Ссылка: /bq/{existing.token}/")
            self.stdout.write("  Пароль не меняется при повторном запуске.")
            return

        query = BusinessQuery.objects.create(
            title="Регистрация юрлиц — ручной флоу и Ддокс",
            intro_text=INTRO_TEXT,
            source_task_path=SOURCE_TASK_PATH,
        )
        password = secrets.token_urlsafe(6)
        query.set_password(password)
        query.save(update_fields=["password_hash"])

        for order, q in enumerate(QUESTIONS):
            BusinessQuestion.objects.create(query=query, order=order, **q)

        self.stdout.write(self.style.SUCCESS(f"Опросник создан: {query.title}"))
        self.stdout.write(f"  Ссылка: /bq/{query.token}/")
        self.stdout.write(f"  Пароль: {password}")
        self.stdout.write(f"  Вопросов: {len(QUESTIONS)}")
